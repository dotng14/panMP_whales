def f(v, d=3):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "–"
    return f"{v:.{d}f}"


def better(a, b, higher=True):
    if not (np.isfinite(a) and np.isfinite(b)):
        return "about the same as"
    if abs(a - b) < 0.005:
        return "about the same as"
    return ("higher than" if a > b else "lower than") if higher else ("lower than" if a < b else "higher than")


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def b_rows(rep, half, keys):
    B = rep["B"][half]
    rows = [
        ["theme accuracy"] + [f(B[k]["theme_accuracy"]) for k in keys],
        ["theme balanced accuracy"] + [f(B[k]["theme_balanced_accuracy"]) for k in keys],
        ["Cohen's κ"] + [f(B[k]["theme_kappa"]) for k in keys],
    ]
    for t in ("15", "30", "60"):
        rows.append([f"song-boundary F1 ±{t} s"] + [f(B[k]["boundaries"][f"tol_{t}s"]["f1"], 2) for k in keys])
    rows += [
        ["songs / complete songs"] + [f"{B[k]['n_songs']} / {B[k]['n_complete_songs']}" for k in keys],
        ["sessions"] + [B[k]["n_sessions"] for k in keys],
        ["fraction of seconds in a session"] + [f(B[k]["session_fraction"]) for k in keys],
    ]
    return rows


def c_rows(rep, half, keys):
    C = rep["C"][half]
    return [
        ["theme coherence (within − adjacent)"] + [f(C[k]["coherence"]["coherence"]) for k in keys],
        ["  within-theme similarity"] + [f(C[k]["coherence"]["within"]) for k in keys],
        ["  adjacent-theme similarity"] + [f(C[k]["coherence"]["between_adjacent"]) for k in keys],
        ["theme identity across songs"] + [f(C[k]["identity"]["identity"]) for k in keys],
        ["theme changes on a novelty peak (precision ±10 s)"] + [f(C[k]["novelty"]["precision"], 2) for k in keys],
        ["novelty peaks hit by a theme change (recall ±10 s)"] + [f(C[k]["novelty"]["recall"], 2) for k in keys],
        ["theme changes"] + [C[k]["novelty"]["n_changes"] for k in keys],
        ["longest run of one theme (min)"] + [f(C[k]["longest_theme_run_s"] / 60, 1) for k in keys],
        ["complete songs: median length (s)"] + [f(C[k]["regularity"]["median_length_s"], 0) for k in keys],
        ["complete songs: length CV"] + [f(C[k]["regularity"]["length_cv"], 2) for k in keys],
    ]


